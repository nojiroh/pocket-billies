def svg(rows):
    rows = [r for r in rows.strip('\n').split('\n')]
    d = ''.join(f'M{x} {y}h1v1h-1z' for y, r in enumerate(rows) for x, c in enumerate(r) if c == '#')
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 12 12" shape-rendering="crispEdges"><path d="{d}" fill="#000"/></svg>'


if __name__ == '__main__':
    made = []
    for k, rows in ICONS.items():
        f = OUT / f'{k}.svg'
        if f.exists(): continue
        f.write_text(svg(rows)); made.append(k)
    print('icons written:', ', '.join(made) or 'none (all exist)')
