#!/usr/bin/env python3
"""Regenerate every image in game/art from the procedural sources in tools/src.
Usage:  python3 tools/build-art.py            (needs: pip install playwright && playwright install chromium)
Writes PNG/SVG files plus game/art/manifest.js and game/art/rigs.js (frame rectangles and skeletons)."""
import base64, json, os, sys, time
from playwright.sync_api import sync_playwright
HERE=os.path.dirname(os.path.abspath(__file__)); GAME=os.path.join(HERE,'..','game')
SRC=['data.js','core.js','pixel.js','beast.js','anatomy.js','anim.js','plans.js','design.js','scene.js','map.js']
def page_html():
    js='\n'.join(open(os.path.join(HERE,'src',f),encoding='utf8').read() for f in SRC)+'\n'+open(os.path.join(GAME,'js','trainer.js'),encoding='utf8').read()+'\n'+open(os.path.join(HERE,'export.js'),encoding='utf8').read()
    p=os.path.join(HERE,'export.html')
    open(p,'w',encoding='utf8').write('<!doctype html><meta charset="utf-8"><body><div id="app"></div><script>'+js+'</script></body>')
    return p
def write(files):
    for f in files:
        out=os.path.join(GAME,f['path']); os.makedirs(os.path.dirname(out),exist_ok=True)
        if 'url' in f: open(out,'wb').write(base64.b64decode(f['url'].split(',',1)[1]))
        else: open(out,'w',encoding='utf8').write(f['text'])
    return len(files)
def main():
    p=page_html(); t0=time.time(); n=0
    with sync_playwright() as pw:
        b=pw.chromium.launch(); pg=b.new_page(); errs=[]; pg.on('pageerror',lambda e:errs.append(str(e)))
        pg.goto('file://'+p); pg.wait_for_timeout(300)
        if errs: print(errs); sys.exit(1)
        ids=pg.evaluate('DEX'); rigs={}
        for i,sp in enumerate(ids):
            r=pg.evaluate('id=>EXPORT.species(id)',sp); n+=write(r['files']); rigs[sp]=r['rig']
            print(f'  billionaire {i+1}/{len(ids)} {sp}',end='\r')
        print()
        man={}
        r=pg.evaluate('EXPORT.icons()'); n+=write(r['files']); man['icons']=r['man']
        for k in ['ui','coins','eggs','people','map','bg']: n+=write(pg.evaluate(f'EXPORT.{k}()')); print('  '+k)
        r=pg.evaluate('EXPORT.battle()'); n+=write(r['files']); man['battle']=r['man']; print('  battle')
        open(os.path.join(GAME,'art','manifest.js'),'w').write('/* generated by tools/build-art.py: atlas rectangles and stage layouts */\nwindow.ARTMAN='+json.dumps(man,separators=(',',':'))+';\n')
        open(os.path.join(GAME,'art','rigs.js'),'w').write('/* generated by tools/build-art.py: billionaire skeletons; frames are [x,y,w,h] in each atlas PNG */\nwindow.RIGS='+json.dumps(rigs,separators=(',',':'))+';\n')
        if errs: print('errors:',errs)
        b.close()
    os.remove(p)
    print(f'wrote {n} files in {time.time()-t0:.1f}s')
if __name__=='__main__': main()
