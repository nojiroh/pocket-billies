#!/usr/bin/env python3
"""Draws only the billionaires you name (from the procedural designs in tools/src) and adds them to game/art,
leaving every other picture alone, including ones edited by hand in the Studio.

    python3 tools/build-art-species.py yacht0 yacht1 yacht2     # these species
    python3 tools/build-art-species.py --line yacht gill        # every stage of these lines
    python3 tools/build-art-species.py --missing                # every species that has no sheet yet

Writes game/art/billionaires/<id>.png (+ _back, _gold, _back_gold) and merges their skeletons into game/art/rigs.js.
Needs Playwright with Chromium, like tools/build-art.py."""
import importlib.util, json, os, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location('ba', ROOT / 'tools' / 'build-art.py'); BA = importlib.util.module_from_spec(spec); spec.loader.exec_module(BA)


def main():
    from playwright.sync_api import sync_playwright
    args = sys.argv[1:]
    p = BA.page_html()
    rigs_path = ROOT / 'game' / 'art' / 'rigs.js'
    txt = rigs_path.read_text(); rigs = json.loads(txt[txt.index('window.RIGS=') + len('window.RIGS='):].rstrip().rstrip(';'))
    with sync_playwright() as pw:
        b = pw.chromium.launch(); pg = b.new_page(); errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.goto('file://' + p); pg.wait_for_timeout(300)
        if errs: print(errs); sys.exit(1)
        dex = pg.evaluate('DEX')
        if '--missing' in args: ids = [d for d in dex if d not in rigs]
        elif '--line' in args: lines = [a for a in args if a != '--line']; ids = [d for d in dex if any(d.startswith(l) and d[len(l):].isdigit() for l in lines)]
        else: ids = [a for a in args if a in dex]
        bad = [a for a in args if not a.startswith('--') and a not in dex and '--line' not in args]
        if bad: print('unknown species:', ', '.join(bad))
        n = 0
        for sp in ids:
            r = pg.evaluate('id=>EXPORT.species(id)', sp); n += BA.write(r['files']); rigs[sp] = r['rig']; print('  drew', sp)
        b.close()
    os.remove(p)
    rigs_path.write_text('/* generated by tools/build-art.py: billionaire skeletons; frames are [x,y,w,h] in each atlas PNG */\nwindow.RIGS=' + json.dumps(rigs, separators=(',', ':')) + ';\n')
    print(f'wrote {n} files for {len(ids)} species; rigs.js now has {len(rigs)}')
    if errs: print('errors:', errs)


if __name__ == '__main__':
    main()
