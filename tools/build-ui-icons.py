def rgb(h):
    return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))


def mix(a, b, t):
    a, b = rgb(a), rgb(b)
    return '#%02X%02X%02X' % tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3))


def render(rows):
    """the 36 x 36 picture of one grid: {(x, y): '#RRGGBB'}"""
    def at(x, y):
        return rows[y][x] if 0 <= x < FRONT and 0 <= y < FRONT and rows[y][x] != '.' else ''
    px = {}
    for k in range(DEPTH, 0, -1):  # the side, far shade first
        for y in range(SIZE):
            for x in range(SIZE):
                m = at(x - k, y - k)
                if m and not at(x, y):
                    px[(x, y)] = mix(PALETTE[m], SHADOW, SIDE[k - 1])
    front = [(x, y) for y in range(FRONT) for x in range(FRONT) if at(x, y)]
    mid = sum(x + y for x, y in front) / len(front)
    for x, y in front:
        m = at(x, y)
        c = PALETTE[m]
        if at(x + 1, y) not in ('', m) or at(x, y + 1) not in ('', m):
            px[(x, y)] = mix(c, SHADOW, SEAM)
        elif at(x, y - 1) != m or at(x - 1, y) != m:
            px[(x, y)] = mix(c, WHITE, LIT)
        else:
            px[(x, y)] = mix(c, WHITE, PALE) if x + y < mid else c
    return px


def svg(rows):
    """one path of horizontal runs per colour"""
    px = render(rows)
    paths = {}
    for y in range(SIZE):
        x = 0
        while x < SIZE:
            c = px.get((x, y))
            if c:
                n = 1
                while px.get((x + n, y)) == c:
                    n += 1
                paths[c] = paths.get(c, '') + f'M{x} {y}h{n}v1h-{n}z'
                x += n
            else:
                x += 1
    body = ''.join(f'<path d="{d}" fill="{c}"/>' for c, d in sorted(paths.items()))
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {SIZE} {SIZE}" shape-rendering="crispEdges">'
            f'{body}</svg>\n')


def main():
    bad = []
    for name, rows in ICONS.items():
        assert len(rows) == FRONT and all(len(r) == FRONT for r in rows), name
        assert all(ch in PALETTE or ch == '.' for r in rows for ch in r), name
        f = OUT / f'{name}.svg'
        text = svg(rows)
        if '--check' in sys.argv:
            if not f.exists() or f.read_text() != text:
                bad.append(name)
        else:
            f.write_text(text)
    if bad:
        print('icons differ from tools/build-ui-icons.py: ' + ', '.join(bad))
        sys.exit(1)
    print(f'{len(ICONS)} icons' + (' match their grids' if '--check' in sys.argv else ' written'))


if __name__ == '__main__':
    main()
