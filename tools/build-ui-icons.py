def svg(rows):
    """one path of horizontal runs (smaller than one square per pixel)"""
    d = ''
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            if row[x] == '#':
                n = 1
                while x + n < len(row) and row[x + n] == '#':
                    n += 1
                d += f'M{x} {y}h{n}v1h-{n}z'
                x += n
            else:
                x += 1
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 12 12" shape-rendering="crispEdges">'
            f'<path d="{d}" fill="#000"/></svg>\n')


def main():
    bad = []
    for name, rows in ICONS.items():
        assert len(rows) == 12 and all(len(r) == 12 for r in rows), name
        f = OUT / f'{name}.svg'
        text = svg(rows)
        if '--check' in sys.argv:
            if not f.exists() or f.read_text() != text:
                bad.append(name)
        else:
            f.write_text(text)
    if bad:
        print('icons differ from tools/build-ui-icons.py: ' + ', '.join(bad))
        sys.exit(1)
    print(f'{len(ICONS)} icons' + (' match their grids' if '--check' in sys.argv else ' written'))


if __name__ == '__main__':
    main()
